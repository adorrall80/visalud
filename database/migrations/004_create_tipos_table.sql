CREATE TABLE tipos (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  proceso_id BIGINT UNSIGNED NOT NULL,
  codigo VARCHAR(50) NOT NULL,
  nombre VARCHAR(100) NOT NULL,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT uk_tipos_proceso_codigo UNIQUE (proceso_id, codigo),
  CONSTRAINT uk_tipos_proceso_nombre UNIQUE (proceso_id, nombre),
  CONSTRAINT fk_tipos_proceso FOREIGN KEY (proceso_id) REFERENCES procesos(id) ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
